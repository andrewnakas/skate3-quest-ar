//! The retail per-material collision table at `0x8302D6E8`, read out of the decrypted retail
//! image (see `docs/audio-object-registry.md` for the dump recipe). Each entry is 16 bytes:
//! `+0` the material's collision sound id (`-1` = the material makes no collision sound) and
//! `+8` the 64-bit AttribSys key of its material record, whose class is
//! `D40CB4C0FFE45676`. `sub_824965D0` indexes this table directly and rejects anything outside
//! `0..MATERIAL_COUNT`, which is why 143 is the "no material" sentinel everywhere else in the
//! contact code.
//!
//! This is `.data`, not tuning: retail ships it inside the executable, so it is baked here the
//! way `inputs::SPEED_SCALES` bakes its image constants. The *categories* are deliberately not
//! baked -- they live in the owner's vault and are read at load time by
//! [`super::collision_states::CollisionMaterials::load`].

